import fs from 'fs';
const NM = '/home/box/apps/gltftools/node_modules';
const THREE = await import(NM + '/three/build/three.module.js');
const { GLTFLoader } = await import(NM + '/three/examples/jsm/loaders/GLTFLoader.js');
const { MeshoptDecoder } = await import(NM + '/three/examples/jsm/libs/meshopt_decoder.module.js');
await MeshoptDecoder.ready;
const b = fs.readFileSync(process.argv[2]); const l = new GLTFLoader(); l.setMeshoptDecoder(MeshoptDecoder);
const g = await new Promise((res, rej) => l.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength), '', res, rej));
const S = g.scene; S.updateMatrixWorld(true);
const names = []; S.traverse(o => names.push(o.name + (o.isMesh ? '[M]' : '')));
console.log('NODES', names.filter(n => /ladder|hatch|deck|rail|ship|cam|board|foot/i.test(n)).join(' '));
const C = S.getObjectByName('Ship_Center').getWorldPosition(new THREE.Vector3());
const LAD = 330 * Math.PI / 180, LU = [Math.cos(LAD), Math.sin(LAD)], LT = [-LU[1], LU[0]];
const toUTZ = v => { const bx = v.x - C.x, by = -(v.z - C.z); return [bx * LU[0] + by * LU[1], bx * LT[0] + by * LT[1], v.y]; };
const tris = []; const v = new THREE.Vector3();
S.traverse(o => { if (!o.isMesh) return; const p = o.geometry.attributes.position, ix = o.geometry.index;
  const n = ix ? ix.count : p.count; let anc = o; let tier = false; while (anc) { if (/^Tier_/.test(anc.name)) tier = true; anc = anc.parent; } if (tier) return;
  for (let i = 0; i < n; i += 3) { const P = [0, 1, 2].map(k => { v.fromBufferAttribute(p, ix ? ix.getX(i + k) : i + k).applyMatrix4(o.matrixWorld); return toUTZ(v); });
    const cu = (P[0][0] + P[1][0] + P[2][0]) / 3, ct = (P[0][1] + P[1][1] + P[2][1]) / 3, cz = (P[0][2] + P[1][2] + P[2][2]) / 3;
    if (cu > 3.0 && cu < 6.5 && Math.abs(ct) < 2.2 && cz > 18 && cz < 25) tris.push([o.name, P]); } });
fs.writeFileSync(process.argv[3], JSON.stringify({ C: [C.x, C.y, C.z], tris }));
console.log('tris near deck', tris.length);
